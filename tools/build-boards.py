"""Build complete word-hunt solutions from ENABLE and the common-English list."""
import json
import random
import sys
from pathlib import Path

dice = "AAEEGN ABBJOO ACHOPS AFFKPS AOOTTW CIMOTU DEILRX DELRVY DISTTY EEGHNW EEINSU EHRTVW EIOSST ELRTTY HIMNQU HLNNRZ".split()
neighbors = [[j for j in range(16) if 0 < max(abs(i // 4 - j // 4), abs(i % 4 - j % 4)) <= 1] for i in range(16)]
source, common_source = map(Path, sys.argv[1:3])
common = set(common_source.read_text().upper().split())
root = {}
for word in source.read_text().upper().split():
    if 3 <= len(word) <= 17:
        node = root
        for letter in word:
            node = node.setdefault(letter, {})
        node["."] = word


def solutions(board):
    words = set()
    def walk(i, used, node):
        node = node.get(board[i])
        if node and board[i] == "Q":
            node = node.get("U")
        if not node:
            return
        if "." in node:
            words.add(node["."])
        used |= 1 << i
        for j in neighbors[i]:
            if not used & (1 << j):
                walk(j, used, node)
    for i in range(16):
        walk(i, 0, root)
    return words


rng = random.Random(9510267)
fields = []
seen = set()
while len(fields) < 384:
    rng.shuffle(dice)
    board = "".join(rng.choice(die) for die in dice)
    if board in seen:
        continue
    words = solutions(board)
    familiar = words & common
    if len(words) < 75 or len(familiar) < 22:
        continue
    if sum(len(w) >= 6 for w in familiar) < 3 or not any(len(w) >= 7 for w in familiar):
        continue
    seen.add(board)
    fields.append([board, " ".join(sorted(words))])
out = Path(__file__).resolve().parents[1] / "docs" / "boards.mjs"
out.write_text("// Generated by tools/build-boards.py from the ENABLE word list.\nexport const FIELDS = [\n" +
               ",\n".join("  " + json.dumps(field) for field in fields) + "\n];\n")
print(f"{len(fields)} boards; valid word counts {min(len(f[1].split()) for f in fields)}–{max(len(f[1].split()) for f in fields)}")
